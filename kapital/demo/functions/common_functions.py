from pathlib import Path
import datetime
import os
BASE_DIR = Path(__file__).resolve().parent.parent


def find_recent_date(file_name="portfel", max_days_back=366):
    folder_path = BASE_DIR / "datasets" / file_name / "svod"


    today = datetime.date.today()
    for i in range(max_days_back):
        active_date = str(today - datetime.timedelta(days=i))
        if file_name == 'balans':
            filepath = folder_path/f"{file_name}_{active_date}.parquet"        
        else:    
            filepath = folder_path/f"svod_{active_date}.parquet"        
        if os.path.isfile(filepath):
            return active_date
    raise FileNotFoundError(f"No processed file found in the last {max_days_back} days.")



def format_number(value):
    try:
        value = float(value)
        """Format large numbers to B (billions) or T (trillions)."""
        if abs(value) >= 1_000_000_000_000:
            return f"{value / 1_000_000_000_000:.1f} Трлн."
        elif abs(value) >= 1_000_000_000:
            return f"{value / 1_000_000_000:.1f} Млрд."
        elif abs(value) >= 1_000_000:
            return f"{value / 1_000_000:.1f} Млн."
        return f"{value:,.0f} Сум"
    except (ValueError, TypeError):
        return value


